// The counter commits to the contents of the nonce file. We also include the
// tally and two more files (tree, sigs). With the contents of the nonce file
// (and the manifest) one can verify that all the other data is correct.
#[derive(Clone, TlsDeserialize, TlsSerialize, TlsSize, Debug)]
pub struct CandidateResults {
    // b3sum of nonce file.  File is sorted and unique, len=tally*NONCE_LEN.
    pub nonces: [u8; 32],
    pub tally: u32,
    pub sigs: [u8; 32],
    // pub tree: [u8; 32],
}

pub fn render_manifest(manifest: &ElectionManifest) -> Markup {
    html! {
        details {
            summary { "Show manifest" }
            table {
                tr { td { b { "Election ID" } } td { pre { (manifest.hash()) } } }
                tr { td { b { "Name" } } td { (manifest.name()) } }
                tr { td { b { "Registration closes" } } td { (manifest.registration_closes().to_string()) } }
                tr { td { b { "Voting starts" } } td { (manifest.voting_period().start.to_string()) } }
                tr { td { b { "Voting ends" } } td { (manifest.voting_period().end.to_string()) } }
                tr { td { b { "# voters" } } td { (manifest.n_voters) } }
                @for c in manifest.candidates.iter() {
                    tr { td { b { (c.name()) } } td { pre { (c.pubkey().to_pem().unwrap()) } } }
                }
            }
        }
    }
}
