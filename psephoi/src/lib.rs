impl serde::Serialize for Election {
    fn serialize<S>(&self, serializer: S) -> std::prelude::v1::Result<S::Ok, S::Error>
    where
        S: serde::Serializer,
    {
        serializer.serialize_str(&self.to_string())
    }
}

impl<'de> serde::Deserialize<'de> for Election {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        struct V;
        impl<'de> serde::de::Visitor<'de> for V {
            type Value = Election;
            fn expecting(&self, f: &mut std::fmt::Formatter) -> std::fmt::Result {
                write!(f, "43 base64url characters")
            }
            fn visit_str<E>(self, v: &str) -> std::prelude::v1::Result<Self::Value, E>
            where
                E: serde::de::Error,
            {
                let x =
                    Base64UrlUnpadded::decode_vec(v).map_err(|e| E::custom(format!("{e:#}")))?;
                let bytes = x.try_into().map_err(|_| E::custom("Wrong length"))?;

                let hash = Hash::from_bytes(bytes);
                Ok(Election(hash))
            }
        }
        deserializer.deserialize_str(V)
    }
}
impl fmt::Display for Election {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", Base64UrlUnpadded::encode_string(self.0.as_bytes()))
    }
}

impl ElectionManifest {
    pub fn from_bytes(bytes: &[u8]) -> Result<Self> {
        Ok(Self::tls_deserialize_exact(bytes)?)
    }
    pub fn to_bytes(&self) -> Vec<u8> {
        self.tls_serialize_detached().unwrap()
    }
    pub fn hash(&self) -> Election {
        let bytes = self.to_bytes();
        Election(blake3::hash(&bytes))
    }
    pub fn name(&self) -> &str {
        str::from_utf8(self.name.as_slice()).unwrap()
    }

    pub fn registration_closes(&self) -> Timestamp {
        Timestamp::from_second(match self.reg_while_voting {
            RegWhileVoting::Disallow => self.voting_start,
            RegWhileVoting::Allow => self.voting_end,
        } as i64)
        .unwrap()
    }

    pub fn voting_period(&self) -> Range<Timestamp> {
        Timestamp::from_second(self.voting_start as i64).unwrap()
            ..Timestamp::from_second(self.voting_end as i64).unwrap()
    }
}

#[derive(Copy, Clone, Linearize, Debug, PartialEq, Eq)]
pub enum Phase {
    Registration,
    Voting,
    Finished,
}
impl fmt::Display for Phase {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Phase::Registration => f.write_str("registration"),
            Phase::Voting => f.write_str("voting"),
            Phase::Finished => f.write_str("finished"),
        }
    }
}

impl CandidateManifest {
    pub fn name(&self) -> &str {
        str::from_utf8(self.name.as_slice()).unwrap()
    }
    pub fn pubkey(&self) -> PublicKey {
        PublicKey::from_spki(self.pubkey.as_slice()).unwrap()
    }
}

