pub const KEYLEN: usize = 2048; // bits
pub const NONCE_LEN: usize = 16;
pub const SIG_LEN: usize = KEYLEN / 8;

/// RSABSSA-SHA384-PSS-Deterministic
#[derive(Debug, serde::Serialize, serde::Deserialize)]
pub struct KeyPair {
    pub pk: PublicKey,
    pub sk: SecretKey,
}
pub type PublicKey = blind_rsa_signatures::PublicKey<Sha384, PSS, Deterministic>;
pub type SecretKey = blind_rsa_signatures::SecretKey<Sha384, PSS, Deterministic>;

impl KeyPair {
    pub fn generate() -> Result<Self> {
        let keypair = blind_rsa_signatures::KeyPair::generate(&mut rng(), KEYLEN)?;
        Ok(KeyPair {
            pk: keypair.pk,
            sk: keypair.sk,
        })
    }
}

/// Describes an election.  Published ahead-of-time, before registration or
/// voting.
#[derive(Clone, Debug, TlsSerialize, TlsDeserialize, TlsSize)]
pub struct ElectionManifest {
    pub name: TlsByteVecU16,
    // Sorted alphabetically by candidate name
    pub candidates: TlsVecU16<CandidateManifest>,
    pub n_voters: u32,
    pub voting_start: u64, // epoch secs
    pub voting_end: u64,   // epoch secs
    pub reg_while_voting: RegWhileVoting,
    // TODO: Counter pubkey
}

/// Does this election allow registration to continue during the voting period?
#[derive(Copy, Clone, Debug, TlsSerialize, TlsDeserialize, TlsSize, PartialEq, Eq)]
#[repr(u8)]
pub enum RegWhileVoting {
    Disallow = 0,
    Allow = 1,
    // WaitForFullRegistrationBeforeStartingVote = 2
}

#[derive(Clone, Debug, TlsSerialize, TlsDeserialize, TlsSize)]
pub struct CandidateManifest {
    pub name: TlsByteVecU16,
    pub pubkey: TlsByteVecU16,
}

