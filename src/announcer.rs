use crate::{AppState, Candidate, ElectionState, registrar::CandidateState};
use axum::{
    extract::{Path, State},
    http::{StatusCode, header},
    response::Response,
};
use core::fmt;
use maud::html;
use serde::Deserialize;
use std::{
    collections::HashMap,
    sync::{Arc, Mutex},
};
use tls_codec::{Serialize, TlsByteVecU16, TlsDeserialize, TlsSerialize, TlsSize, TlsVecU16};

#[derive(Default)]
pub struct AnnouncerState {
    /// Pre-rendered manifests, by hash.  Derived from `elections`
    pub manifests: HashMap<Election, Vec<u8>>,
}

/// Describes an election.  Published ahead-of-time, before registration or
/// voting.
#[derive(Clone, Debug, TlsSerialize, TlsDeserialize, TlsSize)]
pub struct ElectionManifest {
    name: TlsByteVecU16,
    candidates: TlsVecU16<CandidateManifest>,
    // dates
}
#[derive(Clone, Debug, TlsSerialize, TlsDeserialize, TlsSize)]
pub struct CandidateManifest {
    name: TlsByteVecU16,
    pubkey: TlsByteVecU16,
}

/// Names an election.  Generated by hashing the manifest
#[derive(Copy, Clone, PartialEq, Eq, Hash, Debug)]
pub struct Election(blake3::Hash);
impl<'de> Deserialize<'de> for Election {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        struct V;
        impl<'de> serde::de::Visitor<'de> for V {
            type Value = Election;
            fn expecting(&self, f: &mut std::fmt::Formatter) -> std::fmt::Result {
                write!(f, "64 hex characters")
            }
            fn visit_str<E>(self, v: &str) -> std::prelude::v1::Result<Self::Value, E>
            where
                E: serde::de::Error,
            {
                blake3::Hash::from_hex(v)
                    .map(Election)
                    .map_err(|e| E::custom(format!("{e:#}")))
            }
        }
        deserializer.deserialize_str(V)
    }
}
impl fmt::Display for Election {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "election {}", self.0)
    }
}

impl ElectionManifest {
    pub fn bytes(&self) -> Vec<u8> {
        self.tls_serialize_detached().unwrap()
    }
    pub fn hash(&self) -> Election {
        let bytes = self.bytes();
        Election(blake3::hash(&bytes))
    }
}

impl ElectionState {
    pub fn manifest(&self) -> ElectionManifest {
        ElectionManifest {
            name: self.name.as_bytes().into(),
            candidates: self.candidates.iter().map(|(k, v)| v.manifest(k)).collect(),
        }
    }
}

impl CandidateState {
    fn manifest(&self, name: &Candidate) -> CandidateManifest {
        CandidateManifest {
            name: name.0.as_bytes().into(),
            pubkey: self.keypair.pk.to_spki().unwrap().into(),
        }
    }
}

pub async fn list_elections(State(state): State<Arc<Mutex<AppState>>>) -> String {
    let state = state.lock().unwrap();
    let out = html! {
        (maud::DOCTYPE)
        ul {
            @for (hash, state) in &state.registrar.elections {
                li { (hash) ": " (state.name) }
            }
        }
    };
    out.into_string()
}

pub async fn get_manifest(
    State(state): State<Arc<Mutex<AppState>>>,
    Path(election): Path<Election>,
) -> Response {
    let state = state.lock().unwrap();
    let Some(manifest) = state.announcer.manifests.get(&election) else {
        return Response::builder()
            .status(StatusCode::NOT_FOUND)
            .body(format!("{election}: No such election").into())
            .unwrap();
    };
    Response::builder()
        .header(header::CACHE_CONTROL, "public, max-age=31536000, immutable")
        .header(header::CONTENT_TYPE, "application/vnd.psephoi.manifest")
        .body(manifest.clone().into())
        .unwrap()
}
